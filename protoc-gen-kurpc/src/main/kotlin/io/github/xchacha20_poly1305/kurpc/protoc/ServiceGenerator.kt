package io.github.xchacha20_poly1305.kurpc.protoc

import com.google.protobuf.DescriptorProtos.FileDescriptorProto
import com.google.protobuf.DescriptorProtos.MethodDescriptorProto
import com.google.protobuf.DescriptorProtos.SourceCodeInfo
import com.squareup.kotlinpoet.AnnotationSpec
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.ParameterSpec
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.UNIT

private val CALL_INVOKER = ClassName(KURPC_PACKAGE, "CallInvoker")
private val CALL_OPTIONS = ClassName(KURPC_PACKAGE, "CallOptions")
private val METHOD_DESCRIPTOR = ClassName(KURPC_PACKAGE, "MethodDescriptor")
private val FLOW = ClassName("kotlinx.coroutines.flow", "Flow")

/** Field numbers in `descriptor.proto`, the steps of a [SourceCodeInfo.Location] path. */
private const val FILE_SERVICE_FIELD = 6
private const val SERVICE_METHOD_FIELD = 2

private const val CLIENT_PROPERTY = "invoker"

private enum class CallKind(val function: String, val streamsRequests: Boolean, val streamsResponses: Boolean) {
    UNARY("unary", streamsRequests = false, streamsResponses = false),
    SERVER_STREAMING("serverStreaming", streamsRequests = false, streamsResponses = true),
    CLIENT_STREAMING("clientStreaming", streamsRequests = true, streamsResponses = false),
    BIDI_STREAMING("bidiStreaming", streamsRequests = true, streamsResponses = true),
    ;

    /** The typed extension in kurpc's `Method.kt`; KotlinPoet imports it. */
    val member: MemberName = MemberName(KURPC_PACKAGE, function)

    companion object {
        fun of(method: MethodDescriptorProto): CallKind = when {
            method.clientStreaming && method.serverStreaming -> BIDI_STREAMING
            method.clientStreaming -> CLIENT_STREAMING
            method.serverStreaming -> SERVER_STREAMING
            else -> UNARY
        }
    }
}

/**
 * `<Service>Kurpc.kt` in the package [runtime] has for [file]: the object `<Service>Kurpc` with one
 * `MethodDescriptor` per method, and `<Service>Client`, which makes the calls on a `CallInvoker`.
 */
internal class ServiceGenerator(
    private val file: FileDescriptorProto,
    private val serviceIndex: Int,
    private val runtime: MessageRuntime,
) {
    private val service = file.getService(serviceIndex)
    private val packageName = runtime.kotlinPackage(file)
    private val serviceName = if (file.`package`.isEmpty()) service.name else "${file.`package`}.${service.name}"
    private val descriptorsName = ClassName(packageName, "${service.name}Kurpc")
    private val clientName = ClassName(packageName, "${service.name}Client")
    private val comments: Map<List<Int>, SourceCodeInfo.Location> =
        file.sourceCodeInfo.locationList.associateBy { it.pathList }

    fun generate(): FileSpec = FileSpec.builder(descriptorsName)
        .addFileComment("Generated by protoc-gen-kurpc from %L. Do not edit.", file.name)
        // A deprecated method's client function reads its deprecated descriptor.
        .addAnnotation(AnnotationSpec.builder(Suppress::class).addMember("%S", "DEPRECATION").build())
        .addType(descriptors())
        .addType(client())
        .addFunction(runtime.codecFunction())
        .build()

    private fun descriptors(): TypeSpec {
        val builder = TypeSpec.objectBuilder(descriptorsName)
            .addKdoc("Method descriptors of `%L`.", serviceName)
            .addProperty(
                PropertySpec.builder("SERVICE_NAME", String::class, KModifier.CONST)
                    .initializer("%S", serviceName)
                    .build(),
            )
        for (method in service.methodList) {
            val property = PropertySpec.builder(
                propertyName(method),
                METHOD_DESCRIPTOR.parameterizedBy(runtime.type(method.inputType), runtime.type(method.outputType)),
            )
                .initializer(
                    "%T(%S, %L, %L)",
                    METHOD_DESCRIPTOR,
                    "/$serviceName/${method.name}",
                    runtime.codec(method.inputType),
                    runtime.codec(method.outputType),
                )
            if (method.options.deprecated) {
                property.addAnnotation(deprecated("The method"))
            }
            builder.addProperty(property.build())
        }
        return builder.build()
    }

    private fun client(): TypeSpec {
        val builder = TypeSpec.classBuilder(clientName)
            .primaryConstructor(FunSpec.constructorBuilder().addParameter(CLIENT_PROPERTY, CALL_INVOKER).build())
            .addProperty(
                PropertySpec.builder(CLIENT_PROPERTY, CALL_INVOKER, KModifier.PRIVATE)
                    .initializer(CLIENT_PROPERTY)
                    .build(),
            )
        val serviceComment = leadingComment(listOf(FILE_SERVICE_FIELD, serviceIndex))
        if (serviceComment != null) {
            builder.addKdoc("%L", serviceComment)
        } else {
            builder.addKdoc("Client of `%L`.", serviceName)
        }
        if (service.options.deprecated) {
            builder.addAnnotation(deprecated("The service"))
        }
        service.methodList.forEachIndexed { methodIndex, method ->
            builder.addFunction(clientFunction(method, methodIndex))
        }
        return builder.build()
    }

    private fun clientFunction(method: MethodDescriptorProto, methodIndex: Int): FunSpec {
        val kind = CallKind.of(method)
        val requestType = runtime.type(method.inputType)
        val responseType = runtime.type(method.outputType)
        val requestParameter = when {
            kind.streamsRequests -> ParameterSpec("requests", FLOW.parameterizedBy(requestType))
            // A request without content needs no argument.
            requestType == UNIT -> ParameterSpec.builder("request", requestType).defaultValue("%T", UNIT).build()
            else -> ParameterSpec("request", requestType)
        }
        val builder = FunSpec.builder(propertyName(method))
            .addParameter(requestParameter)
            .addParameter(
                ParameterSpec.builder("options", CALL_OPTIONS)
                    .defaultValue("%T()", CALL_OPTIONS)
                    .build(),
            )
            .returns(if (kind.streamsResponses) FLOW.parameterizedBy(responseType) else responseType)
            .addStatement(
                "return %N.%M(%T.%N, %N, options)",
                CLIENT_PROPERTY,
                kind.member,
                descriptorsName,
                propertyName(method),
                requestParameter,
            )
        if (!kind.streamsResponses) {
            builder.addModifiers(KModifier.SUSPEND)
        }
        leadingComment(listOf(FILE_SERVICE_FIELD, serviceIndex, SERVICE_METHOD_FIELD, methodIndex))?.let {
            builder.addKdoc("%L", it)
        }
        if (method.options.deprecated) {
            builder.addAnnotation(deprecated("The method"))
        }
        return builder.build()
    }

    private fun deprecated(subject: String): AnnotationSpec = AnnotationSpec.builder(Deprecated::class)
        .addMember("%S", "$subject is deprecated in ${file.name}.")
        .build()

    /** Comment text on its own lines, with whatever would end or nest the KDoc block defused. */
    private fun leadingComment(path: List<Int>): String? {
        val text = comments[path]?.leadingComments?.trimIndent()?.trim()
        if (text.isNullOrEmpty()) {
            return null
        }
        return text.replace("*/", "*&#47;").replace("/*", "&#47;*")
    }
}

private fun propertyName(method: MethodDescriptorProto): String = lowerCamelCase(method.name)

/**
 * `GetVersion` → `getVersion`, `URLTest` → `urlTest`, `HTTP` → `http`, `get_version` →
 * `getVersion`: a leading acronym is lowered as a whole, except the capital that starts the next
 * word.
 */
internal fun lowerCamelCase(name: String): String {
    val camel = name.split('_')
        .filter { it.isNotEmpty() }
        .mapIndexed { index, word -> if (index == 0) word else word.replaceFirstChar(Char::uppercaseChar) }
        .joinToString("")
    var upperEnd = 0
    while (upperEnd < camel.length && camel[upperEnd].isUpperCase()) {
        upperEnd++
    }
    val nextWordStarts = upperEnd > 1 && upperEnd < camel.length && camel[upperEnd].isLowerCase()
    val lowerEnd = if (nextWordStarts) upperEnd - 1 else upperEnd
    return camel.substring(0, lowerEnd).lowercase() + camel.substring(lowerEnd)
}

/** Where protoc writes the file, below its `--kurpc_out` directory. */
internal val FileSpec.relativePath: String
    get() = if (packageName.isEmpty()) "$name.kt" else "${packageName.replace('.', '/')}/$name.kt"
