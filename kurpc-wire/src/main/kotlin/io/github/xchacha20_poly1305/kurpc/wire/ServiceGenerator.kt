package io.github.xchacha20_poly1305.kurpc.wire

import com.squareup.kotlinpoet.AnnotationSpec
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.ParameterSpec
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.UNIT
import com.squareup.wire.kotlin.KotlinGenerator
import com.squareup.wire.schema.Options
import com.squareup.wire.schema.ProtoMember
import com.squareup.wire.schema.ProtoType
import com.squareup.wire.schema.Rpc
import com.squareup.wire.schema.Schema
import com.squareup.wire.schema.Service

private val CALL_INVOKER = ClassName(KURPC_PACKAGE, "CallInvoker")
private val CALL_OPTIONS = ClassName(KURPC_PACKAGE, "CallOptions")
private val METHOD_DESCRIPTOR = ClassName(KURPC_PACKAGE, "MethodDescriptor")
private val FLOW = ClassName("kotlinx.coroutines.flow", "Flow")

private const val CLIENT_PROPERTY = "invoker"

private enum class CallKind(
    val function: String,
    val streamsRequests: Boolean,
    val streamsResponses: Boolean,
) {
    UNARY("unary", streamsRequests = false, streamsResponses = false),
    SERVER_STREAMING("serverStreaming", streamsRequests = false, streamsResponses = true),
    CLIENT_STREAMING("clientStreaming", streamsRequests = true, streamsResponses = false),
    BIDI_STREAMING("bidiStreaming", streamsRequests = true, streamsResponses = true);

    /** The typed extension in kurpc's `Method.kt`; KotlinPoet imports it. */
    val member: MemberName = MemberName(KURPC_PACKAGE, function)

    companion object {
        fun of(method: Rpc): CallKind =
            when {
                method.requestStreaming && method.responseStreaming -> BIDI_STREAMING
                method.requestStreaming -> CLIENT_STREAMING
                method.responseStreaming -> SERVER_STREAMING
                else -> UNARY
            }
    }
}

/**
 * `<Service>Kurpc.kt` in the Kotlin package of the service: the object `<Service>Kurpc` with one
 * `MethodDescriptor` per method, and `<Service>Client`, which makes the calls on a `CallInvoker`.
 */
internal class ServiceGenerator(
    private val service: Service,
    schema: Schema,
) {
    private val runtime = WireRuntime(schema)
    private val packageName = KotlinGenerator(schema).generatedServiceName(service).packageName
    private val serviceName = service.type.toString()
    private val descriptorsName = ClassName(packageName, "${service.name}Kurpc")
    private val clientName = ClassName(packageName, "${service.name}Client")

    fun generate(): FileSpec =
        FileSpec.builder(descriptorsName)
            .addFileComment("Generated by kurpc-wire from %L. Do not edit.", service.location.path)
            // A deprecated method's client function reads its deprecated descriptor.
            .addAnnotation(
                AnnotationSpec.builder(Suppress::class)
                    .addMember("%S", "DEPRECATION")
                    .build(),
            )
            .addType(descriptors())
            .addType(client())
            .addFunction(runtime.codecFunction())
            .build()

    private fun descriptors(): TypeSpec {
        val builder = TypeSpec.objectBuilder(descriptorsName)
            .addKdoc("Method descriptors of `%L`.", serviceName)
            .addProperty(
                PropertySpec.builder("SERVICE_NAME", String::class, KModifier.CONST)
                    .initializer("%S", serviceName)
                    .build(),
            )
        for (method in service.rpcs) {
            val property = PropertySpec.builder(
                propertyName(method),
                METHOD_DESCRIPTOR.parameterizedBy(
                    runtime.type(requireNotNull(method.requestType)),
                    runtime.type(requireNotNull(method.responseType)),
                ),
            )
                .initializer(
                    "%T(%S, %L, %L)",
                    METHOD_DESCRIPTOR,
                    "/$serviceName/${method.name}",
                    runtime.codec(requireNotNull(method.requestType)),
                    runtime.codec(requireNotNull(method.responseType)),
                )
            if (method.options.isDeprecated(Options.METHOD_OPTIONS)) {
                property.addAnnotation(deprecated("The method"))
            }
            builder.addProperty(property.build())
        }
        return builder.build()
    }

    private fun client(): TypeSpec {
        val builder = TypeSpec.classBuilder(clientName)
            .primaryConstructor(
                FunSpec.constructorBuilder()
                    .addParameter(CLIENT_PROPERTY, CALL_INVOKER)
                    .build(),
            )
            .addProperty(
                PropertySpec.builder(CLIENT_PROPERTY, CALL_INVOKER, KModifier.PRIVATE)
                    .initializer(CLIENT_PROPERTY)
                    .build(),
            )
        val serviceComment = comment(service.documentation)
        if (serviceComment != null) {
            builder.addKdoc("%L", serviceComment)
        } else {
            builder.addKdoc("Client of `%L`.", serviceName)
        }
        if (service.options.isDeprecated(Options.SERVICE_OPTIONS)) {
            builder.addAnnotation(deprecated("The service"))
        }
        service.rpcs.forEach { method ->
            builder.addFunction(clientFunction(method))
        }
        return builder.build()
    }

    private fun clientFunction(method: Rpc): FunSpec {
        val kind = CallKind.of(method)
        val requestType = runtime.type(requireNotNull(method.requestType))
        val responseType = runtime.type(requireNotNull(method.responseType))
        val requestParameter =
            when {
                kind.streamsRequests -> ParameterSpec("requests", FLOW.parameterizedBy(requestType))

                // A request without content needs no argument.
                requestType == UNIT -> {
                    ParameterSpec.builder("request", requestType).defaultValue("%T", UNIT).build()
                }

                else -> ParameterSpec("request", requestType)
            }
        val builder =
            FunSpec.builder(propertyName(method))
                .addParameter(requestParameter)
                .addParameter(
                    ParameterSpec.builder("options", CALL_OPTIONS)
                        .defaultValue("%T()", CALL_OPTIONS)
                        .build(),
                )
                .returns(
                    if (kind.streamsResponses) {
                        FLOW.parameterizedBy(responseType)
                    } else {
                        responseType
                    },
                )
                .addStatement(
                    "return %N.%M(%T.%N, %N, options)",
                    CLIENT_PROPERTY,
                    kind.member,
                    descriptorsName,
                    propertyName(method),
                    requestParameter,
                )
        if (!kind.streamsResponses) {
            builder.addModifiers(KModifier.SUSPEND)
        }
        comment(method.documentation)?.let {
            builder.addKdoc("%L", it)
        }
        if (method.options.isDeprecated(Options.METHOD_OPTIONS)) {
            builder.addAnnotation(deprecated("The method"))
        }
        return builder.build()
    }

    private fun deprecated(subject: String): AnnotationSpec =
        AnnotationSpec.builder(Deprecated::class)
            .addMember("%S", "$subject is deprecated in ${service.location.path}.")
            .build()

    private fun comment(documentation: String): String? =
        documentation
            .trim()
            .takeIf { it.isNotEmpty() }
            ?.replace("*/", "*&#47;")
            ?.replace("/*", "&#47;*")
}

private fun Options.isDeprecated(type: ProtoType): Boolean =
    get(ProtoMember.get(type, "deprecated"))?.toString() == "true"

private fun propertyName(method: Rpc): String = lowerCamelCase(method.name)

/**
 * `GetVersion` → `getVersion`, `URLTest` → `urlTest`, `HTTP` → `http`, `get_version` →
 * `getVersion`: a leading acronym is lowered as a whole, except the capital that starts the next
 * word.
 */
internal fun lowerCamelCase(name: String): String {
    val camel = name.split('_')
        .filter { it.isNotEmpty() }
        .mapIndexed { index, word ->
            if (index == 0) {
                word
            } else {
                word.replaceFirstChar(Char::uppercaseChar)
            }
        }
        .joinToString("")
    var upperEnd = 0
    while (upperEnd < camel.length && camel[upperEnd].isUpperCase()) {
        upperEnd++
    }
    val nextWordStarts = upperEnd > 1 && upperEnd < camel.length && camel[upperEnd].isLowerCase()
    val lowerEnd = if (nextWordStarts) {
        upperEnd - 1
    } else {
        upperEnd
    }
    return camel.substring(0, lowerEnd).lowercase() + camel.substring(lowerEnd)
}

